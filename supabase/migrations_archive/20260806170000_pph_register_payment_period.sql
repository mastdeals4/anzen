CREATE OR REPLACE FUNCTION public.trg_recompute_from_payment_voucher()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_expense_id uuid;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    IF COALESCE(OLD.pph_amount, 0) > 0 THEN
      PERFORM public.recompute_pph_periods_for_date(OLD.voucher_date);
    END IF;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    IF COALESCE(NEW.pph_amount, 0) > 0 THEN
      PERFORM public.recompute_pph_periods_for_date(NEW.voucher_date);
    END IF;
  END IF;

  FOR v_expense_id IN
    SELECT DISTINCT va.finance_expense_id
    FROM public.voucher_allocations va
    JOIN public.finance_expenses fe ON fe.id = va.finance_expense_id
    WHERE va.payment_voucher_id = COALESCE(NEW.id, OLD.id)
      AND va.finance_expense_id IS NOT NULL
      AND (
        COALESCE(fe.pph_amount, 0) > 0
        OR COALESCE(fe.pib_pph_amount, 0) > 0
        OR fe.expense_category = 'pph_import'
      )
  LOOP
    PERFORM public.recompute_pph_periods_for_date(public.get_expense_pph_period_date(v_expense_id));
  END LOOP;
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.trg_recompute_pph_from_voucher_allocation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_expense_id uuid;
  v_voucher_id uuid;
  v_date date;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') AND OLD.finance_expense_id IS NOT NULL THEN
    v_expense_id := OLD.finance_expense_id;
    PERFORM 1 FROM public.finance_expenses fe
    WHERE fe.id = v_expense_id
      AND (COALESCE(fe.pph_amount, 0) > 0 OR COALESCE(fe.pib_pph_amount, 0) > 0 OR fe.expense_category = 'pph_import');
    IF NOT FOUND THEN
      v_expense_id := NULL;
    END IF;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') AND v_expense_id IS NOT NULL THEN
    v_voucher_id := OLD.payment_voucher_id;
    SELECT voucher_date INTO v_date FROM public.payment_vouchers WHERE id = v_voucher_id;
    PERFORM public.recompute_pph_periods_for_date(v_date);
    PERFORM public.recompute_pph_periods_for_date(public.get_expense_pph_period_date(v_expense_id));
    SELECT COALESCE(due_date, expense_date) INTO v_date FROM public.finance_expenses WHERE id = v_expense_id;
    PERFORM public.recompute_pph_periods_for_date(v_date);
  END IF;

  IF TG_OP IN ('INSERT', 'UPDATE') AND NEW.finance_expense_id IS NOT NULL THEN
    v_expense_id := NEW.finance_expense_id;
    PERFORM 1 FROM public.finance_expenses fe
    WHERE fe.id = v_expense_id
      AND (COALESCE(fe.pph_amount, 0) > 0 OR COALESCE(fe.pib_pph_amount, 0) > 0 OR fe.expense_category = 'pph_import');
    IF NOT FOUND THEN
      v_expense_id := NULL;
    END IF;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND v_expense_id IS NOT NULL THEN
    v_voucher_id := NEW.payment_voucher_id;
    SELECT voucher_date INTO v_date FROM public.payment_vouchers WHERE id = v_voucher_id;
    PERFORM public.recompute_pph_periods_for_date(v_date);
    PERFORM public.recompute_pph_periods_for_date(public.get_expense_pph_period_date(v_expense_id));
    SELECT COALESCE(due_date, expense_date) INTO v_date FROM public.finance_expenses WHERE id = v_expense_id;
    PERFORM public.recompute_pph_periods_for_date(v_date);
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_recompute_pph_from_voucher_allocation ON public.voucher_allocations;
CREATE TRIGGER trg_recompute_pph_from_voucher_allocation
AFTER INSERT OR UPDATE OR DELETE ON public.voucher_allocations
FOR EACH ROW EXECUTE FUNCTION public.trg_recompute_pph_from_voucher_allocation();


-- Create any newly required destination months, then recalculate derived
-- Register snapshots only.  Source documents, allocations, bank links,
-- journals, tax payments, and filings are not modified.
DO $$
DECLARE
  v_date date;
  v_period_id uuid;
BEGIN
  FOR v_date IN
    SELECT DISTINCT public.get_expense_pph_period_date(fe.id)
    FROM public.finance_expenses fe
    WHERE fe.approval_status = 'approved'
      AND (
        COALESCE(fe.pph_amount, 0) > 0
        OR COALESCE(fe.pib_pph_amount, 0) > 0
        OR fe.expense_category = 'pph_import'
      )
  LOOP
    PERFORM public.recompute_pph_periods_for_date(v_date);
  END LOOP;

  FOR v_period_id IN
    SELECT id FROM public.tax_periods WHERE tax_type <> 'PPN'
  LOOP
    PERFORM public.compute_period_ppn(v_period_id);
  END LOOP;
END;
$$;

